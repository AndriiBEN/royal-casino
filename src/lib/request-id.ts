/**
 * RFC 4122 v4 id for duplicate-transaction protection. Each form render or game round
 * gets one; retrying the same request reuses it, so the server applies it once.
 * Falls back to getRandomValues where randomUUID is unavailable (plain-HTTP LAN access).
 */
export function newRequestId(): string {
  const c = globalThis.crypto;
  if (typeof c?.randomUUID === "function") return c.randomUUID();
  const b = c.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
